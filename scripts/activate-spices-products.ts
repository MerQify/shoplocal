async function main() {
  const f = flags(process.argv.slice(2));
  if (!f.file || !f.key) {
    console.error(
      "Usage: npx tsx scripts/activate-spices-products.ts <secrets-file> <url-key> [--apply --confirm-host <host>] [--production]",
    );
    process.exit(1);
  }

  const url = readVar(f.file, f.key);
  if (!url) throw new Error(`${f.key} not found in ${f.file}`);

  const hostMatch = url.match(/@([^:/?]+)/);
  const actualHost = hostMatch ? hostMatch[1] : "(unknown)";
  console.log(`Target database host: ${actualHost}`);

  if (f.apply) {
    if (!f.confirmHost) {
      console.error(`Refusing --apply without --confirm-host <host>. Target is: ${actualHost}`);
      process.exit(1);
    }
    if (f.confirmHost !== actualHost) {
      console.error(
        `Host mismatch: --confirm-host was "${f.confirmHost}" but target is "${actualHost}"`,
      );
      process.exit(1);
    }
    if (f.production && !f.file.includes("production")) {
      console.error(
        `Safety check: --production passed but secrets file "${f.file}" does not look like production.`,
      );
      process.exit(1);
    }
  }

  const prisma = new PrismaClient({ adapter: new PrismaNeon({ connectionString: url }) });

  try {
    const vendor = await prisma.vendor.findFirst({
      where: { slug: "aheed-food-centre" },
      select: { id: true, name: true, slug: true },
    });
    if (!vendor) throw new Error("Vendor 'aheed-food-centre' not found");
    const vendorId = vendor.id;

    const spicesCat = await prisma.category.findFirst({
      where: { vendorId, slug: "spices-masalas" },
      select: { id: true, name: true, slug: true },
    });
    if (!spicesCat) throw new Error("Category 'spices-masalas' not found");

    const brands = await prisma.brand.findMany({
      where: { vendorId },
      select: { id: true, name: true, slug: true },
    });
    const brandMap = new Map(brands.map((b) => [b.slug, b]));

    // Combine all updates
    const allItems = [...LAZIZA_ITEMS, ...SHAN_ITEMS, ...SPICES_ITEMS];
    console.log(`\nTotal items to process: ${allItems.length}`);
    console.log(`  - Laziza: ${LAZIZA_ITEMS.length}`);
    console.log(`  - Shan: ${SHAN_ITEMS.length}`);
    console.log(`  - Spices: ${SPICES_ITEMS.length}`);

    // Fetch existing product data
    const productIds = Array.from(new Set(allItems.map((i) => i.productId)));
    const existingProducts = await prisma.product.findMany({
      where: { id: { in: productIds }, vendorId },
      include: {
        inventory: true,
        brand: true,
        category: true,
      },
    });
    const productMap = new Map(existingProducts.map((p) => [p.id, p]));

    console.log(
      `Found ${existingProducts.length} of ${productIds.length} target products in database.`,
    );
    if (existingProducts.length !== productIds.length) {
      const missing = productIds.filter((id) => !productMap.has(id));
      console.error(`Missing products: ${missing.join(", ")}`);
      throw new Error(`Some product IDs could not be found in DB.`);
    }

    let updatedCount = 0;
    let auditLogsCreated = 0;

    for (const item of allItems) {
      const p = productMap.get(item.productId)!;
      const brand = brandMap.get(item.brandSlug);
      if (!brand) throw new Error(`Brand with slug '${item.brandSlug}' not found.`);

      const netContent = { amount: item.netContentAmount, unit: item.netContentUnit };
      const unitPricePencePerBaseUnit = deriveUnitPricePenceForSort(item.pricePence, netContent);

      if (f.apply) {
        // Update product
        await prisma.product.update({
          where: { id: p.id },
          data: {
            name: item.cleanName,
            basePrice: item.pricePence,
            categoryId: spicesCat.id,
            brandId: brand.id,
            netContentAmount: item.netContentAmount,
            netContentUnit: item.netContentUnit,
            unitPricePencePerBaseUnit,
            isActive: true,
          },
        });
        updatedCount++;

        // Ensure inventory is UNTRACKED
        if (p.inventory) {
          if (p.inventory.stockMode !== "UNTRACKED") {
            const prevMode = p.inventory.stockMode;
            const prevQty = p.inventory.quantity;
            await prisma.inventory.update({
              where: { id: p.inventory.id },
              data: { stockMode: "UNTRACKED" },
            });

            await prisma.inventoryAuditLog.create({
              data: {
                vendorId,
                productId: p.id,
                inventoryId: p.inventory.id,
                previousQuantity: prevQty,
                newQuantity: prevQty,
                changeAmount: 0,
                previousStockMode: prevMode,
                newStockMode: "UNTRACKED",
                source: "EXCEL_IMPORT",
                reason: `Excel stock activation: ${item.sheet}`,
              },
            });
            auditLogsCreated++;
          }
        } else {
          const inv = await prisma.inventory.create({
            data: {
              vendorId,
              productId: p.id,
              quantity: 0,
              stockMode: "UNTRACKED",
              lowStockThreshold: 5,
            },
          });
          await prisma.inventoryAuditLog.create({
            data: {
              vendorId,
              productId: p.id,
              inventoryId: inv.id,
              previousQuantity: 0,
              newQuantity: 0,
              changeAmount: 0,
              previousStockMode: "UNKNOWN",
              newStockMode: "UNTRACKED",
              source: "EXCEL_IMPORT",
              reason: `Excel stock activation: ${item.sheet}`,
            },
          });
          auditLogsCreated++;
        }
      } else {
        // Dry run log
        console.log(
          `[DRY RUN] [${item.sheet} R${item.rowNumber}] "${item.cleanName}" | £${(item.pricePence / 100).toFixed(2)} | ${item.netContentAmount}${item.netContentUnit} | Brand: ${brand.name} | Product: ${p.id} (prev: "${p.name}", active: ${p.isActive}, cat: ${p.category?.slug})`,
        );
        updatedCount++;
      }
    }

    console.log(`\n================== SUMMARY ==================`);
    console.log(`Mode: ${f.apply ? "APPLIED" : "DRY RUN"}`);
    console.log(`Database Host: ${actualHost}`);
    console.log(`Products processed/updated: ${updatedCount}`);
    console.log(`Inventory audit logs created: ${auditLogsCreated}`);
    console.log(`Spices & Masalas Category: ${spicesCat.name} (${spicesCat.id})`);
    console.log(`=============================================\n`);
  } finally {
    await prisma.$disconnect();
  }
}

main().catch(console.error);
